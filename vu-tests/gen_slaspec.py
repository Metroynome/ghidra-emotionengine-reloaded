# constructors require VUMODE 0. ImportVuMicrocode.java and the VU microcode analyzer place each
# microprogram in an overlay at its VU micro memory addresses and set VUMODE there. VU0 micro mode
# uses the COP2 registers that VU0 macro mode uses; VU1 has its own registers. Data memory is where
# the EE sees it: VU0's at 0x11004000, VU1's at 0x1100c000.


#!/usr/bin/env python3
"""gen_slaspec.py VARIANT OUT.slaspec : write the VU micro mode SLEIGH specification.

VARIANT is vu0 or vu1 for a standalone language, or embed for vumicro.sinc, which holds both units
for the R5900 language (where the VUMODE context selects them; see embed()). The units differ only
in memory sizes and, inside R5900, in registers: VU0 micro mode uses the COP2 registers. The tables
are regular (16 dest masks, 32 flag sets, 32 registers, four lanes), so they are generated here.
Decoding and display follow the reference disassembler, PS2SDK dvp-objdump; vu-tests/compare.py
checks them.

Semantics
- Both halves of an instruction execute together, so both read the register state from before
  it. The upper half's sources (fs, ft, q, i) are snapshotted, the lower half runs, then the upper
  half runs on the snapshot. When both write one register, the upper result is kept.
- vf00 reads as (0, 0, 0, 1.0) and vi00 as 0; writes to them are discarded.
- Each dest lane is computed into a temporary and written only when its mask bit is set.
- Branches and jumps run the upper half, then the delay slot, then transfer. bal and jalr are
  calls, jr vi15 is a return, and the E bit ends the program after its delay slot.
- Data memory is its own space, addressed in 16-byte units that wrap at its size.
- Branch and jump targets wrap at the end of micro memory (16 KB on VU1, 4 KB on VU0), as the
  VU's PC does. Branch targets are shown unwrapped, as the reference shows them.
- rnext steps R's 23-bit LFSR exactly. EFU transcendentals and xgkick are p-code operations.
- add, sub, mul, madd, msub (every form) and opmula/opmsub set the MAC flags and status bits 0-3
  with their sticky copies (see flags()). Results stay IEEE: where the VU clamps an overflow or
  flushes an underflow, the result here is infinite or denormal, though the flags match. div, sqrt
  and rsqrt set the I and D status bits; sqrt and rsqrt use the absolute value. Other
  instructions leave the flags alone.
- Not modelled: pipeline latencies. Q, P and flag results are visible to the very next
  instruction, where the VU makes them visible only after their latency.
"""

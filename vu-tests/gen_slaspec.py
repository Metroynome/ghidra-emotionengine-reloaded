#!/usr/bin/env python3
"""gen_slaspec.py OUT.slaspec : write the VU micro mode SLEIGH specification.

The instruction tables are regular (16 dest masks, 32 flag sets, 32 registers), so they are
generated here; the opcode lists follow the reference disassembler's output.
"""
import sys

LANES = 'xyzw'


def dest_text(mask):
	# Bit 3 is x, bit 0 is w.
	return ''.join(LANES[i] for i in range(4) if mask & (8 >> i))


def flags_text(v):
	# Bits, high to low: i e m d t.
	s = ''.join(c for i, c in enumerate('iemdt') if v & (16 >> i))
	return '[%s]' % s if s else ''


out = []
w = out.append
w('''# PlayStation 2 Vector Unit, micro mode. Generated by vu-tests/gen_slaspec.py; edit that instead.
#
# Each instruction is 64 bits: the lower instruction is the first word in memory and the upper
# instruction the second. The listing follows PS2SDK dvp-objdump: "upper<tab>lower". Branch
# offsets count 64-bit words from the next instruction.

define endian=little;
define alignment=8;

define space ram type=ram_space size=4 default;
define space register type=register_space size=4;

define register offset=0x0 size=4 [ pc ];
''')
vf = ' '.join('vf%02d' % i for i in range(32))
# The hardware has 16 VI registers, but the 5-bit fields decode as vi00-vi31 in the reference.
vi = ' '.join('vi%02d' % i for i in range(32))
lanes = ' '.join('vf%02d_%s' % (i, c) for i in range(32) for c in LANES)
w('define register offset=0x1000 size=16 [ %s acc ];' % vf)
w('define register offset=0x1000 size=4 [ %s acc_x acc_y acc_z acc_w ];' % lanes)
w('define register offset=0x2000 size=2 [ %s ];' % vi)
w('define register offset=0x3000 size=4 [ q p i r status mac clip ];')
w('''
define token instr(64)
	# Lower instruction (first word).
	l_word = (0,31)
	l_op7 = (25,31)
	l_dest = (21,24)
	l_ft = (16,20)
	l_fs = (11,15)
	l_fd = (6,10)
	l_it = (16,20)
	l_is = (11,15)
	l_id = (6,10)
	l_it4 = (16,19)
	l_is4 = (11,14)
	l_id4 = (6,9)
	l_ithi = (20,20)
	l_ishi = (15,15)
	l_idhi = (10,10)
	l_op6 = (0,5)
	l_op11 = (0,10)
	l_fsf = (21,22)
	l_ftf = (23,24)
	l_imm11 = (0,10) signed dec
	l_imm5 = (6,10) signed dec
	l_lo11 = (0,10)
	l_hi4 = (21,24)
	l_bit21 = (21,21)
	l_imm24 = (0,23) dec
	l_b24 = (24,24)
	l_hi3 = (22,24)
	l_lo6 = (0,5)
	# Upper instruction (second word).
	u_word = (32,63)
	u_flags = (59,63)
	u_i = (63,63)
	u_res = (57,58)
	u_dest = (53,56)
	u_ft = (48,52)
	u_fs = (43,47)
	u_fd = (38,42)
	u_op6 = (32,37)
	u_op4 = (34,37)
	u_bc = (32,33)
	u_op11 = (32,42)
;

attach variables [ l_ft l_fs l_fd u_ft u_fs u_fd ] [ %s ];
attach variables [ l_it l_is l_id ] [ %s ];
''' % (vf, vi))

# Lane and flag text.
# LD2 repeats LD: a constructor can reference a subtable only once.
for name, field in (('UD', 'u_dest'), ('LD', 'l_dest'), ('LD2', 'l_dest')):
	for m in range(16):
		w('%s: "%s" is %s=%d { }' % (name, dest_text(m), field, m))
for m in range(32):
	w('UF: "%s" is u_flags=%d { }' % (flags_text(m), m))
for name, field in (('UBC', 'u_bc'), ('LFSF', 'l_fsf'), ('LFTF', 'l_ftf')):
	for i, c in enumerate(LANES):
		w('%s: "%s" is %s=%d { }' % (name, c, field, i))
w('')
# VI registers only exist for numbers 0-15; the high bit must be clear.
for name, f in (('IT', 'l_it'), ('IS', 'l_is'), ('ID', 'l_id')):
	w('%s: %s is %s { export %s; }' % (name, f, f, f))
w('''
# Upper operands.
UFD: u_fd^UD is u_fd & UD { }
UFS: u_fs^UD is u_fs & UD { }
UFT: u_ft^UD is u_ft & UD { }
UACC: "acc"^UD is UD { }
UBCR: u_ft^UBC is u_ft & UBC { }
''')

# Upper instructions: name, opcode match, operand text.
upper = []
BC = ['add', 'sub', 'madd', 'msub', 'max', 'mini', 'mul']
for i, n in enumerate(BC):
	upper.append(('%s^UBC' % ('"%s"' % n), 'u_op4=%d' % i, 'UFD^","^UFS^","^UBCR'))
for op, n, src in ((0x1c, 'mulq', 'q'), (0x1d, 'maxi', 'i'), (0x1e, 'muli', 'i'), (0x1f, 'minii', 'i'),
		(0x20, 'addq', 'q'), (0x21, 'maddq', 'q'), (0x22, 'addi', 'i'), (0x23, 'maddi', 'i'),
		(0x24, 'subq', 'q'), (0x25, 'msubq', 'q'), (0x26, 'subi', 'i'), (0x27, 'msubi', 'i')):
	upper.append(('"%s"' % n, 'u_op6=0x%x & u_ft=0' % op, 'UFD^","^UFS^",%s"' % src))
for op, n in ((0x28, 'add'), (0x29, 'madd'), (0x2a, 'mul'), (0x2b, 'max'), (0x2c, 'sub'), (0x2d, 'msub'),
		(0x2e, 'opmsub'), (0x2f, 'mini')):
	upper.append(('"%s"' % n, 'u_op6=0x%x' % op, 'UFD^","^UFS^","^UFT'))
for g, n in ((0, 'adda'), (1, 'suba'), (2, 'madda'), (3, 'msuba'), (6, 'mula')):
	upper.append(('"%s"^UBC' % n, 'u_op6>=0x3c & u_fd=%d' % g, 'UACC^","^UFS^","^UBCR'))
for g, n in ((4, 'itof'), (5, 'ftoi')):
	for bc, sfx in enumerate(('0', '4', '12', '15')):
		upper.append(('"%s%s"' % (n, sfx), 'u_op11=0x%x' % (g << 6 | 0x3c | bc), 'UFT^","^UFS'))
for op11, n, src in ((0x1fc, 'mulaq', 'q'), (0x1fe, 'mulai', 'i'), (0x23c, 'addaq', 'q'), (0x23d, 'maddaq', 'q'),
		(0x23e, 'addai', 'i'), (0x23f, 'maddai', 'i'), (0x27c, 'subaq', 'q'), (0x27d, 'msubaq', 'q'),
		(0x27e, 'subai', 'i'), (0x27f, 'msubai', 'i')):
	upper.append(('"%s"' % n, 'u_op11=0x%x & u_ft=0' % op11, 'UACC^","^UFS^",%s"' % src))
for op11, n in ((0x2bc, 'adda'), (0x2bd, 'madda'), (0x2be, 'mula'), (0x2fc, 'suba'), (0x2fd, 'msuba'), (0x2fe, 'opmula')):
	upper.append(('"%s"' % n, 'u_op11=0x%x' % op11, 'UACC^","^UFS^","^UFT'))
upper.append(('"abs"', 'u_op11=0x1fd', 'UFT^","^UFS'))
upper.append(('"clipw"', 'u_op11=0x1ff & u_dest=0xe', 'UFS^","^u_ft^"w"'))

w('# Upper instructions. The u_res bits are always clear.')
for mn, match, ops in upper:
	# Every table and field shown must appear in the pattern.
	need = sorted({t for t in ('UBC', 'UFD', 'UFS', 'UFT', 'UACC', 'UBCR', 'u_ft')
		if __import__('re').search(r'\b%s\b' % t, mn + ' ' + ops)})
	w('UPPER: %s^UF^"."^UD %s is %s & u_res=0 & UF & UD %s{ }' % (mn, ops, match, ''.join('& %s ' % t for t in need)))
w('UPPER: "nop"^UF is u_op11=0x2ff & u_res=0 & u_dest=0 & u_ft=0 & u_fs=0 & UF { }')
# The reference decodes each half on its own and shows an invalid half as *unknown*.
w('UPPER: "*unknown*" is u_word { }')

w('''
# Lower operands.
LFT: l_ft^LD is l_ft & LD { }
LFS: l_fs^LD is l_fs & LD { }
BTARG: dest is l_imm11 [ dest = inst_next + l_imm11 * 8; ] { export *:4 dest; }
IMM15: val is l_hi4 & l_lo11 [ val = (l_hi4 << 11) | l_lo11; ] { export *[const]:2 val; }
IMM12: val is l_bit21 & l_lo11 [ val = (l_bit21 << 11) | l_lo11; ] { export *[const]:2 val; }
''')
lower = []
L7 = 'l_op7=0x%x'
lower += [
	('"lq."^LD LFT^","^l_imm11^"("^IS^")"', L7 % 0x00, ''),
	('"sq."^LD LFS^","^l_imm11^"("^IT^")"', L7 % 0x01, ''),
	('"ilw."^LD IT^","^l_imm11^"("^IS^")"^LD2', L7 % 0x04, ''),
	('"isw."^LD IT^","^l_imm11^"("^IS^")"^LD2', L7 % 0x05, ''),
	('"iaddiu" IT^","^IS^","^IMM15', L7 % 0x08, ''),
	('"isubiu" IT^","^IS^","^IMM15', L7 % 0x09, ''),
	('"fceq vi01,"^l_imm24', L7 % 0x10, '& l_b24=0'),
	('"fcset" l_imm24', L7 % 0x11, '& l_b24=0'),
	('"fcand vi01,"^l_imm24', L7 % 0x12, '& l_b24=0'),
	('"fcor vi01,"^l_imm24', L7 % 0x13, '& l_b24=0'),
	('"fseq" IT^","^IMM12', L7 % 0x14, ''),
	('"fsset" IMM12', L7 % 0x15, ''),
	('"fsand" IT^","^IMM12', L7 % 0x16, ''),
	('"fsor" IT^","^IMM12', L7 % 0x17, ''),
	('"fmeq" IT^","^IS', L7 % 0x18, ''),
	('"fmand" IT^","^IS', L7 % 0x1a, ''),
	('"fmor" IT^","^IS', L7 % 0x1b, ''),
	('"fcget" IT', L7 % 0x1c, ''),
	('"b" BTARG', L7 % 0x20, ''),
	('"bal" IT^","^BTARG', L7 % 0x21, ''),
	('"jr" IS', L7 % 0x24, ''),
	('"jalr" IT^","^IS', L7 % 0x25, ''),
	('"ibeq" IT^","^IS^","^BTARG', L7 % 0x28, ''),
	('"ibne" IT^","^IS^","^BTARG', L7 % 0x29, ''),
	('"ibltz" IS^","^BTARG', L7 % 0x2c, ''),
	('"ibgtz" IS^","^BTARG', L7 % 0x2d, ''),
	('"iblez" IS^","^BTARG', L7 % 0x2e, ''),
	('"ibgez" IS^","^BTARG', L7 % 0x2f, ''),
]
L40 = 'l_op7=0x40 & l_op6=0x%x'
lower += [
	('"iadd" ID^","^IS^","^IT', L40 % 0x30, ''),
	('"isub" ID^","^IS^","^IT', L40 % 0x31, ''),
	('"iaddi" IT^","^IS^","^l_imm5', L40 % 0x32, ''),
	('"iand" ID^","^IS^","^IT', L40 % 0x34, ''),
	('"ior" ID^","^IS^","^IT', L40 % 0x35, ''),
]
LS = 'l_op7=0x40 & l_op11=0x%x'
lower += [
	('"move."^LD LFT^","^LFS', LS % 0x33c, ''),
	('"mr32."^LD LFT^","^LFS', LS % 0x33d, ''),
	('"lqi."^LD LFT^",("^IS^"++)"', LS % 0x37c, ''),
	('"sqi."^LD LFS^",("^IT^"++)"', LS % 0x37d, ''),
	('"lqd."^LD LFT^",(--"^IS^")"', LS % 0x37e, ''),
	('"sqd."^LD LFS^",(--"^IT^")"', LS % 0x37f, ''),
	('"div q,"^l_fs^LFSF^","^l_ft^LFTF', LS % 0x3bc, ''),
	('"sqrt q,"^l_ft^LFTF', LS % 0x3bd, ''),
	('"rsqrt q,"^l_fs^LFSF^","^l_ft^LFTF', LS % 0x3be, ''),
	('"waitq"', LS % 0x3bf, ''),
	('"mtir" IT^","^l_fs^LFSF', LS % 0x3fc, ''),
	('"mfir."^LD LFT^","^IS', LS % 0x3fd, ''),
	('"ilwr."^LD IT^",("^IS^")"^LD2', LS % 0x3fe, ''),
	('"iswr."^LD IT^",("^IS^")"^LD2', LS % 0x3ff, ''),
	('"rnext."^LD LFT^",r"', LS % 0x43c, ''),
	('"rget."^LD LFT^",r"', LS % 0x43d, ''),
	('"rinit r,"^l_fs^LFSF', LS % 0x43e, ''),
	('"rxor r,"^l_fs^LFSF', LS % 0x43f, ''),
	('"mfp."^LD LFT^",p"', LS % 0x67c, ''),
	('"xtop" IT', LS % 0x6bc, ''),
	('"xitop" IT', LS % 0x6bd, ''),
	('"xgkick" IS', LS % 0x6fc, ''),
	('"esadd p,"^l_fs', LS % 0x73c, ''),
	('"ersadd p,"^l_fs', LS % 0x73d, ''),
	('"eleng p,"^l_fs', LS % 0x73e, ''),
	('"erleng p,"^l_fs', LS % 0x73f, ''),
	('"eatanxy p,"^l_fs', LS % 0x77c, ''),
	('"eatanxz p,"^l_fs', LS % 0x77d, ''),
	('"esum p,"^l_fs', LS % 0x77e, ''),
	('"esqrt p,"^l_fs^LFSF', LS % 0x7bc, ''),
	('"ersqrt p,"^l_fs^LFSF', LS % 0x7bd, ''),
	('"ercpr p,"^l_fs^LFSF', LS % 0x7be, ''),
	('"waitp"', LS % 0x7bf, ''),
	('"esin p,"^l_fs^LFSF', LS % 0x7fc, ''),
	('"eatan p,"^l_fs^LFSF', LS % 0x7fd, ''),
	('"eexp p,"^l_fs^LFSF', LS % 0x7fe, ''),
]
# Fields each instruction leaves unused must be clear (measured with vu-tests/bitflip.py).
RESERVED = {
	'b': 'l_dest=0 & l_it=0 & l_is=0', 'bal': 'l_dest=0 & l_is=0',
	'ibeq': 'l_dest=0', 'ibne': 'l_dest=0',
	'ibltz': 'l_dest=0 & l_it=0', 'ibgtz': 'l_dest=0 & l_it=0', 'iblez': 'l_dest=0 & l_it=0', 'ibgez': 'l_dest=0 & l_it=0',
	'jr': 'l_dest=0 & l_it=0 & l_lo11=0', 'jalr': 'l_dest=0 & l_lo11=0',
	'fcget': 'l_dest=0 & l_is=0 & l_lo11=0',
	'fmeq': 'l_dest=0 & l_lo11=0', 'fmand': 'l_dest=0 & l_lo11=0', 'fmor': 'l_dest=0 & l_lo11=0',
	'fseq': 'l_hi3=0 & l_is=0', 'fsand': 'l_hi3=0 & l_is=0', 'fsor': 'l_hi3=0 & l_is=0',
	'fsset': 'l_hi3=0 & l_it=0 & l_is=0 & l_lo6=0',
	'iadd': 'l_dest=0', 'isub': 'l_dest=0', 'iand': 'l_dest=0', 'ior': 'l_dest=0', 'iaddi': 'l_dest=0',
	'esqrt': 'l_ftf=0 & l_ft=0', 'ersqrt': 'l_ftf=0 & l_ft=0', 'ercpr': 'l_ftf=0 & l_ft=0',
	'esin': 'l_ftf=0 & l_ft=0', 'eatan': 'l_ftf=0 & l_ft=0', 'eexp': 'l_ftf=0 & l_ft=0',
	'esadd': 'l_dest=0xe & l_ft=0', 'ersadd': 'l_dest=0xe & l_ft=0', 'eleng': 'l_dest=0xe & l_ft=0',
	'erleng': 'l_dest=0xe & l_ft=0', 'esum': 'l_dest=0xf & l_ft=0',
	'eatanxy': 'l_dest=0xc & l_ft=0', 'eatanxz': 'l_dest=0xa & l_ft=0',
	'mfp': 'l_is=0', 'mtir': 'l_ftf=0', 'rget': 'l_is=0', 'rnext': 'l_is=0',
	'rinit': 'l_ftf=0 & l_ft=0', 'rxor': 'l_ftf=0 & l_ft=0', 'sqrt': 'l_fsf=0 & l_fs=0',
	'waitq': 'l_dest=0 & l_ft=0 & l_fs=0', 'waitp': 'l_dest=0 & l_ft=0 & l_fs=0',
	'xgkick': 'l_dest=0 & l_ft=0', 'xtop': 'l_dest=0 & l_is=0', 'xitop': 'l_dest=0 & l_is=0',
}
w('# Lower instructions.')
for disp, match, extra in lower:
	parts = disp.split(' ', 1)
	text = disp
	# Every table and field referenced in the display must appear in the pattern.
	need = sorted({t for t in ('LD', 'LD2', 'LFT', 'LFS', 'IT', 'IS', 'ID', 'BTARG', 'IMM15', 'IMM12', 'LFSF', 'LFTF',
		'l_imm11', 'l_imm5', 'l_imm24', 'l_fs', 'l_ft') if __import__('re').search(r'\b%s\b' % t, disp)})
	name = __import__('re').match(r'"(\w+)', disp)[1]
	if name in RESERVED:
		extra = (extra + ' & ' + RESERVED[name]).strip()
	w('LOWER: %s is %s %s%s { }' % (text, match, ''.join('& %s ' % t for t in need), extra))
w('LOWER: "nop" is l_word=0x8000033c { }')
w('LOWER: "*unknown*" is l_word { }')
w('''
:^UPPER^"	"^LOWER is UPPER & LOWER & u_i=0 { }
:^UPPER^"	loi "^l_word is UPPER & l_word & u_i=1 { }
''')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')

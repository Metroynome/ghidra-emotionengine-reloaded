# ---- Embedding in the R5900 language ----
def regmap():
	"""Standalone register name -> name inside R5900, and the registers to define there.

	VU0 micro mode uses the COP2 registers VU0 macro mode uses (cop2.sinc): vfN with lanes vfNx..,
	vuACC, vuQ, P, vuI, vuR, vuStatus_32, vuMAC and vuCF, and vi0-vi15 through 16-bit aliases. The
	rest of VU0 and all of VU1 get registers of their own.
	"""
	pre = variant + '_'
	m = {}
	defs = []
	base = 0x8000 if variant == 'vu1' else 0xa000
	if variant == 'vu0':
		for i in range(32):
			m['vf%02d' % i] = 'vf%d' % i
			for c in LANES:
				m['vf%02d_%s' % (i, c)] = 'vf%d%s' % (i, c)
		m['acc'] = 'vuACC'
		for c in LANES:
			m['acc_%s' % c] = 'vuACC%s' % c
		m.update(q='vuQ', p='P', i='vuI', r='vuR', status='vuStatus_32', mac='vuMAC', clip='vuCF')
		defs.append('define register offset=0x4000 size=2 [ %s ];' % ' '.join(
			'vu0_vi%02d _' % i for i in range(16)))
		for i in range(16):
			m['vi%02d' % i] = 'vu0_vi%02d' % i
		own16 = ['vfsink', 'us', 'ut']
		vi_own = ['vi%02d' % i for i in range(16, 32)] + ['visink']
	else:
		own16 = ['vf%02d' % i for i in range(32)] + ['acc', 'vfsink', 'us', 'ut']
		vi_own = ['vi%02d' % i for i in range(32)] + ['visink']
	defs.append('define register offset=0x%x size=16 [ %s ];' % (base, ' '.join(pre + n for n in own16)))
	defs.append('define register offset=0x%x size=4 [ %s ];' % (base, ' '.join(
		'%s%s_%s' % (pre, n, c) for n in own16 for c in LANES)))
	for n in own16:
		m[n] = pre + n
		for c in LANES:
			m['%s_%s' % (n, c)] = '%s%s_%s' % (pre, n, c)
	defs.append('define register offset=0x%x size=2 [ %s ];' % (base + 0x800, ' '.join(pre + n for n in vi_own)))
	words = ['uq', 'ui', 'lbr_target', 'vu_end', 'tr_x', 'tr_y', 'tr_z', 'tr_w', 'tr_ea', 'vu_sp']
	if variant == 'vu1':
		words = ['q', 'p', 'i', 'r', 'status', 'mac', 'clip'] + words
	defs.append('define register offset=0x%x size=4 [ %s ];' % (base + 0x900, ' '.join(pre + n for n in words)))
	defs.append('define register offset=0x%x size=2 [ %s ];' % (base + 0xa00, ' '.join(
		pre + n for n in ('vu_top', 'vu_itop'))))
	defs.append('define register offset=0x%x size=1 [ %slbr_cond ];' % (base + 0xb00, pre))
	for n in vi_own + words + ['vu_top', 'vu_itop', 'lbr_cond']:
		m[n] = pre + n
	return m, defs


def embed(text):
	"""Renames this unit's tables, token, fields and registers so both units fit in R5900."""
	regs, defs = regmap()
	names = dict(regs)
	for t in set(re.findall(r'^(\w+):', text, re.M)):
		names[t] = variant.upper() + '_' + t
	for f in re.findall(r'^\s*(\w+)\s*=\s*\(\d+,\d+\)', text, re.M):
		names[f] = variant + '_' + f
	names['instr'] = variant + '_instr'
	names['endslot'] = 'VU_ENDSLOT'
	pattern = re.compile(r'\b(%s)\b' % '|'.join(sorted(map(re.escape, names), key=len, reverse=True)))
	# Rename outside quoted display text only.
	pieces = text.split('"')
	for k in range(0, len(pieces), 2):
		pieces[k] = pattern.sub(lambda mm: names[mm.group(1)], pieces[k])
	head = '# ---- %s ----\n' % variant.upper() + '\n'.join(defs) + '\n'
	return head + '"'.join(pieces)


